"""Klickt das Portal im Browser durch (375 px). Aufruf: python3 tools/e2e_portal.py <basis-url> <screenshot-ordner>"""
import sys, pathlib
from playwright.sync_api import sync_playwright

base = sys.argv[1].rstrip('/')
shots = pathlib.Path(sys.argv[2]); shots.mkdir(exist_ok=True)
errors = []

def answer_all(page):
    while True:
        page.wait_for_selector('[data-pruefen], [data-fertig]')
        if page.locator('[data-fertig]').count():
            return
        page.locator('[data-antwort]').nth(0).click()
        page.click('[data-pruefen]')
        page.click('[data-weiter]')

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    page = b.new_context(viewport={'width': 375, 'height': 800}).new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(base + '/index.html')
    page.wait_for_selector('[data-lehrjahr="1"]')
    assert 'In welchem Lehrjahr' in page.inner_text('#app')
    page.screenshot(path=str(shots / 'p0-lehrjahr.png'), full_page=True)
    assert not page.locator('#nav').is_visible(), 'Reiter sollten vor der Lehrjahr-Wahl versteckt sein'
    page.click('[data-lehrjahr="1"]')
    page.wait_for_selector('.pfad')
    assert page.locator('#nav').is_visible()
    assert 'Teste hier dein Wissen' in page.inner_text('#app')
    import re
    m = re.search(r'(\d+) Fragen · ca\. (\d+) Min', page.inner_text('#app'))
    assert m and int(m.group(1)) > 0, page.inner_text('#app')
    page.screenshot(path=str(shots / 'p1-start.png'), full_page=True)
    page.click('.wissenstest [data-start="pruefung"]')
    assert 'Wissenstest · 1. Lehrjahr' in page.inner_text('#app')
    page.click('[data-pruefen]')
    assert 'Wähle zuerst' in page.inner_text('#app')
    answer_all(page)
    page.screenshot(path=str(shots / 'p2-auswertung.png'), full_page=True)
    page.click('[data-fertig]')
    page.wait_for_selector('.pfad')
    page.click('#nav a[data-r="lernstand"]')
    page.wait_for_selector('text=Als Nächstes')
    page.screenshot(path=str(shots / 'p3-lernstand.png'), full_page=True)
    page.click('#nav a[data-r="start"]')
    page.wait_for_selector('.pfad')
    assert 'Elektrik-Grundlagen' in page.inner_text('#app')
    gesperrt_lj1 = page.locator('.bereich-kachel.gesperrt').count()
    assert gesperrt_lj1 > 0
    assert 'ab 2. Lehrjahr' in page.inner_text('#app')
    page.screenshot(path=str(shots / 'p4-themen.png'), full_page=True)
    page.locator('a.bereich-kachel').nth(0).click()
    page.wait_for_selector('.themenliste')
    assert page.locator('a.themazeile').count() == 6
    page.screenshot(path=str(shots / 'p4b-bereich.png'), full_page=True)
    page.click('[data-bereichstest]')
    answer_all(page)
    assert 'Auswertung' in page.inner_text('#app')
    page.click('[data-fertig]')
    page.wait_for_selector('.pfad')
    page.goto(base + '/index.html#/bereich/Elektrik-Grundlagen')
    page.wait_for_selector('.themenliste')
    page.locator('a.themazeile').nth(0).click()
    page.wait_for_selector('[data-kurz]')
    page.locator('[data-stern]').nth(0).click()
    page.wait_for_selector('text=Präsentation starten')
    page.wait_for_selector('text=Folien')
    page.locator('[data-nurvideo]').nth(0).click()
    page.wait_for_selector('#overlay video')
    page.screenshot(path=str(shots / 'p5b-video.png'))
    page.click('#video-zu')
    assert page.locator('#overlay').count() == 0
    page.screenshot(path=str(shots / 'p5-thema.png'), full_page=True)
    page.click('[data-kurz]')
    answer_all(page)
    page.click('[data-fertig]')
    page.click('#nav a[data-r="ueben"]')
    page.click('[data-start="uebung"]')
    assert 'mindestens ein Thema' in page.inner_text('#app')
    page.locator('[data-wahl]').nth(0).check()
    page.click('[data-start="uebung"]')
    page.locator('[data-antwort]').nth(0).click(); page.click('[data-pruefen]')
    page.click('[data-abbrechen]')
    page.wait_for_selector('[data-wahl]')
    page.click('footer >> text=Impressum')
    page.wait_for_selector('text=§ 5 DDG')
    assert 'Excel-Datei' in page.inner_text('#app')
    page.click('footer >> text=Datenschutz')
    page.wait_for_selector('text=GitHub Pages')
    page.screenshot(path=str(shots / 'p7-datenschutz.png'), full_page=True)
    vorher = page.evaluate("document.documentElement.classList.contains('light')")
    page.click('#btn-theme')
    if vorher: page.click('#btn-theme')
    assert page.evaluate("document.documentElement.classList.contains('light')")
    assert page.evaluate("localStorage.getItem('lp-theme')") == 'light'
    page.goto(base + '/index.html#/themen')
    page.wait_for_selector('.pfad')
    assert page.evaluate("document.documentElement.classList.contains('light')")
    page.screenshot(path=str(shots / 'p8-themen-hell.png'), full_page=True)
    page.click('#btn-theme')
    assert page.evaluate("localStorage.getItem('lp-theme')") == 'dark'
    page.screenshot(path=str(shots / 'p9-themen-dunkel.png'), full_page=True)
    before = page.evaluate("localStorage.getItem('kfz-lernportal-v1')")
    page.goto(base + '/index.html#/lernstand')
    page.wait_for_selector('text=Als Nächstes')
    assert page.evaluate("localStorage.getItem('kfz-lernportal-v1')") == before and before
    page.click('[data-lehrjahr-aendern]')
    page.click('[data-lehrjahr="2"]')
    page.wait_for_selector('text=2. Lehrjahr')
    page.goto(base + '/index.html#/themen')
    page.wait_for_selector('.pfad')
    assert 0 < page.locator('.bereich-kachel.gesperrt').count() < gesperrt_lj1
    page.goto(base + '/index.html#/thema/Hochvolt%20im%20Kfz')
    page.wait_for_selector('text=freigeschaltet')
    page.goto(base + '/index.html#/lexikon')
    page.wait_for_selector('#lex-q')
    page.fill('#lex-q', 'lima')
    assert page.is_visible('#lex-generator') and not page.is_visible('#lex-spannung')
    page.fill('#lex-q', '')
    page.click('[data-lexbereich="Hochvolt"]')
    assert page.is_visible('#lex-wartungsstecker') and not page.is_visible('#lex-spannung')
    page.screenshot(path=str(shots / 'p10-lexikon.png'), full_page=False)
    page.goto(base + '/index.html#/thema/' + 'Spannung%2C%20Strom%20und%20Widerstand')
    page.click('.lexwort >> nth=0')
    page.wait_for_selector('.lexbox')
    page.click('#lex-mehr')
    page.wait_for_selector('.lexeintrag.markiert')
    page.goto(base + '/multimeter.html')
    page.click('[data-dreh="V="]'); page.click('[data-punkt="B+"]'); page.click('[data-punkt="Masse"]')
    assert '12,6 V' in page.inner_text('#mm')
    page.screenshot(path=str(shots / 'p6-multimeter.png'), full_page=True)
    b.close()

if errors:
    print('PAGE ERRORS', errors); sys.exit(1)
print('E2E OK')
